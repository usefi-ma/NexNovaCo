using Microsoft.AspNetCore.Identity.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;

namespace NexNovaCo.Web.Data;

public sealed class ApplicationDbContext(DbContextOptions<ApplicationDbContext> options)
    : IdentityDbContext<ApplicationUser>(options)
{
    public DbSet<HomeHeroSettings> HomeHeroSettings => Set<HomeHeroSettings>();
    public DbSet<HomeWelcomeSettings> HomeWelcomeSettings => Set<HomeWelcomeSettings>();
    public DbSet<HomeServicesSectionSettings> HomeServicesSectionSettings => Set<HomeServicesSectionSettings>();
    public DbSet<HomeProjectsSectionSettings> HomeProjectsSectionSettings => Set<HomeProjectsSectionSettings>();
    public DbSet<HomeTeamSectionSettings> HomeTeamSectionSettings => Set<HomeTeamSectionSettings>();
    public DbSet<HomeStatistic> HomeStatistics => Set<HomeStatistic>();
    public DbSet<HomePartnersSectionSettings> HomePartnersSectionSettings => Set<HomePartnersSectionSettings>();
    public DbSet<HomeTestimonialsSectionSettings> HomeTestimonialsSectionSettings => Set<HomeTestimonialsSectionSettings>();
    public DbSet<TestimonialEntity> Testimonials => Set<TestimonialEntity>();
    public DbSet<TestimonialInitializationState> TestimonialInitializationStates => Set<TestimonialInitializationState>();

    public DbSet<PartnerEntity> Partners => Set<PartnerEntity>();
    public DbSet<PartnerInitializationState> PartnerInitializationStates => Set<PartnerInitializationState>();

    public DbSet<ServiceEntity> Services => Set<ServiceEntity>();
    public DbSet<HomeFeaturedService> HomeFeaturedServices => Set<HomeFeaturedService>();
    public DbSet<ServiceInitializationState> ServiceInitializationStates => Set<ServiceInitializationState>();

    public DbSet<ProjectEntity> Projects => Set<ProjectEntity>();
    public DbSet<ProjectGalleryImage> ProjectGalleryImages => Set<ProjectGalleryImage>();
    public DbSet<ProjectFeature> ProjectFeatures => Set<ProjectFeature>();
    public DbSet<HomeFeaturedProject> HomeFeaturedProjects => Set<HomeFeaturedProject>();
    public DbSet<ProjectInitializationState> ProjectInitializationStates => Set<ProjectInitializationState>();

    protected override void OnModelCreating(ModelBuilder builder)
    {
        base.OnModelCreating(builder);
        var project = builder.Entity<ProjectEntity>();
        project.ToTable("Projects", table => table.HasCheckConstraint("CK_Projects_Order", "DisplayOrder > 0"));
        project.HasKey(x => x.Id);
        project.HasIndex(x => x.DisplayOrder);
        project.HasIndex(x => x.Slug).IsUnique();
        project.Property(x => x.Slug).IsRequired().HasMaxLength(80).UseCollation("NOCASE");
        project.Property(x => x.Name).IsRequired().HasMaxLength(80);
        project.Property(x => x.Tagline).IsRequired().HasMaxLength(120);
        project.Property(x => x.Description).IsRequired().HasMaxLength(300);
        project.Property(x => x.FullDescription).IsRequired().HasMaxLength(10000);
        project.Property(x => x.ImagePath).IsRequired().HasMaxLength(200);
        project.Property(x => x.Client).HasMaxLength(160);
        project.Property(x => x.Category).HasMaxLength(160);
        project.Property(x => x.Date).HasMaxLength(80);
        project.Property(x => x.Technologies).HasMaxLength(500);
        project.Property(x => x.UpdatedAtUtc).IsConcurrencyToken();
        project.HasMany(x => x.Gallery).WithOne().HasForeignKey(x => x.ProjectId).OnDelete(DeleteBehavior.Cascade);
        project.HasMany(x => x.Features).WithOne().HasForeignKey(x => x.ProjectId).OnDelete(DeleteBehavior.Cascade);
        var gallery = builder.Entity<ProjectGalleryImage>();
        gallery.ToTable("ProjectGalleryImages", table => table.HasCheckConstraint("CK_ProjectGalleryImages_Order", "DisplayOrder > 0"));
        gallery.HasKey(x => x.Id);
        gallery.HasIndex(x => new { x.ProjectId, x.DisplayOrder });
        gallery.Property(x => x.Source).IsRequired().HasMaxLength(200);
        gallery.Property(x => x.Alt).IsRequired().HasMaxLength(200);
        var feature = builder.Entity<ProjectFeature>();
        feature.ToTable("ProjectFeatures", table => table.HasCheckConstraint("CK_ProjectFeatures_Order", "DisplayOrder > 0"));
        feature.HasKey(x => x.Id);
        feature.HasIndex(x => new { x.ProjectId, x.DisplayOrder });
        feature.Property(x => x.Text).IsRequired().HasMaxLength(300);
        var featuredProject = builder.Entity<HomeFeaturedProject>();
        featuredProject.ToTable("HomeFeaturedProjects", table => table.HasCheckConstraint("CK_HomeFeaturedProjects_Order", "DisplayOrder > 0"));
        featuredProject.HasKey(x => x.ProjectId);
        featuredProject.Property(x => x.ProjectId).ValueGeneratedNever();
        featuredProject.HasIndex(x => x.DisplayOrder);
        featuredProject.HasOne(x => x.Project).WithOne(x => x.HomeFeatured).HasForeignKey<HomeFeaturedProject>(x => x.ProjectId).OnDelete(DeleteBehavior.Cascade);
        var projectInitialization = builder.Entity<ProjectInitializationState>();
        projectInitialization.ToTable("ProjectInitializationState", table => table.HasCheckConstraint("CK_ProjectInitializationState_Singleton", "Id = 1"));
        projectInitialization.HasKey(x => x.Id);
        projectInitialization.Property(x => x.Id).ValueGeneratedNever();
        var service = builder.Entity<ServiceEntity>();
        service.ToTable("Services", table => table.HasCheckConstraint("CK_Services_Order", "DisplayOrder > 0"));
        service.HasKey(x => x.Id);
        service.HasIndex(x => x.DisplayOrder);
        service.HasIndex(x => x.ContentKey).IsUnique();
        service.Property(x => x.ContentKey).IsRequired().HasMaxLength(80);
        service.Property(x => x.Name).IsRequired().HasMaxLength(60);
        service.Property(x => x.Tagline).IsRequired().HasMaxLength(80);
        service.Property(x => x.Description).IsRequired().HasMaxLength(200);
        service.Property(x => x.IconPath).IsRequired().HasMaxLength(200);
        service.Property(x => x.UpdatedAtUtc).IsConcurrencyToken();
        var featured = builder.Entity<HomeFeaturedService>();
        featured.ToTable("HomeFeaturedServices", table => table.HasCheckConstraint("CK_HomeFeaturedServices_Order", "DisplayOrder BETWEEN 1 AND 5"));
        featured.HasKey(x => x.ServiceId);
        featured.Property(x => x.ServiceId).ValueGeneratedNever();
        featured.HasIndex(x => x.DisplayOrder);
        featured.HasOne(x => x.Service).WithOne(x => x.HomeFeatured).HasForeignKey<HomeFeaturedService>(x => x.ServiceId).OnDelete(DeleteBehavior.Cascade);
        var serviceInitialization = builder.Entity<ServiceInitializationState>();
        serviceInitialization.ToTable("ServiceInitializationState", table => table.HasCheckConstraint("CK_ServiceInitializationState_Singleton", "Id = 1"));
        serviceInitialization.HasKey(x => x.Id);
        serviceInitialization.Property(x => x.Id).ValueGeneratedNever();
        var hero = builder.Entity<HomeHeroSettings>();
        hero.ToTable("HomeHeroSettings", table => table.HasCheckConstraint("CK_HomeHeroSettings_Singleton", "Id = 1"));
        hero.HasKey(x => x.Id);
        hero.Property(x => x.Id).ValueGeneratedNever();
        hero.Property(x => x.OpeningLine).IsRequired().HasMaxLength(60);
        hero.Property(x => x.EmphasisLine).IsRequired().HasMaxLength(60);
        hero.Property(x => x.ClosingLine).IsRequired().HasMaxLength(60);
        hero.Property(x => x.Description).IsRequired().HasMaxLength(500);
        hero.Property(x => x.CtaLabel).IsRequired().HasMaxLength(60);
        hero.Property(x => x.CtaHref).IsRequired().HasMaxLength(200);
        var welcome = builder.Entity<HomeWelcomeSettings>();
        welcome.ToTable("HomeWelcomeSettings", table => table.HasCheckConstraint("CK_HomeWelcomeSettings_Singleton", "Id = 1"));
        welcome.HasKey(x => x.Id);
        welcome.Property(x => x.Id).ValueGeneratedNever();
        welcome.Property(x => x.Title).IsRequired().HasMaxLength(120);
        welcome.Property(x => x.Introduction).IsRequired().HasMaxLength(500);
        welcome.Property(x => x.ParagraphOne).IsRequired().HasMaxLength(1000);
        welcome.Property(x => x.ParagraphTwo).IsRequired().HasMaxLength(1000);
        welcome.Property(x => x.CtaLabel).IsRequired().HasMaxLength(60);
        welcome.Property(x => x.CtaHref).IsRequired().HasMaxLength(200);
        var services = builder.Entity<HomeServicesSectionSettings>();
        services.ToTable("HomeServicesSectionSettings", table => table.HasCheckConstraint("CK_HomeServicesSectionSettings_Singleton", "Id = 1"));
        services.HasKey(x => x.Id);
        services.Property(x => x.Id).ValueGeneratedNever();
        services.Property(x => x.Title).IsRequired().HasMaxLength(120);
        services.Property(x => x.Description).IsRequired().HasMaxLength(1000);
        var projects = builder.Entity<HomeProjectsSectionSettings>();
        projects.ToTable("HomeProjectsSectionSettings", table => table.HasCheckConstraint("CK_HomeProjectsSectionSettings_Singleton", "Id = 1"));
        projects.HasKey(x => x.Id);
        projects.Property(x => x.Id).ValueGeneratedNever();
        projects.Property(x => x.Title).IsRequired().HasMaxLength(120);
        projects.Property(x => x.Description).IsRequired().HasMaxLength(1000);
        var team = builder.Entity<HomeTeamSectionSettings>();
        team.ToTable("HomeTeamSectionSettings", table => table.HasCheckConstraint("CK_HomeTeamSectionSettings_Singleton", "Id = 1"));
        team.HasKey(x => x.Id);
        team.Property(x => x.Id).ValueGeneratedNever();
        team.Property(x => x.Title).IsRequired().HasMaxLength(120);
        team.Property(x => x.Introduction).IsRequired().HasMaxLength(500);
        team.Property(x => x.Highlight).IsRequired().HasMaxLength(300);
        team.Property(x => x.Description).IsRequired().HasMaxLength(1000);
        team.Property(x => x.CtaLabel).IsRequired().HasMaxLength(60);
        team.Property(x => x.CtaHref).IsRequired().HasMaxLength(200);
        var statistics = builder.Entity<HomeStatistic>();
        statistics.ToTable("HomeStatistics", table =>
        {
            table.HasCheckConstraint("CK_HomeStatistics_FixedSlots", "Id BETWEEN 1 AND 4 AND DisplayOrder = Id");
            table.HasCheckConstraint("CK_HomeStatistics_Value", "Value BETWEEN 0 AND 9999");
        });
        statistics.HasKey(x => x.Id);
        statistics.Property(x => x.Id).ValueGeneratedNever();
        statistics.HasIndex(x => x.DisplayOrder).IsUnique();
        statistics.Property(x => x.Label).IsRequired().HasMaxLength(32);
        var partners = builder.Entity<HomePartnersSectionSettings>();
        partners.ToTable("HomePartnersSectionSettings", table => table.HasCheckConstraint("CK_HomePartnersSectionSettings_Singleton", "Id = 1"));
        partners.HasKey(x => x.Id);
        partners.Property(x => x.Id).ValueGeneratedNever();
        partners.Property(x => x.Title).IsRequired().HasMaxLength(120);
        partners.Property(x => x.Description).IsRequired().HasMaxLength(1000);
        var testimonials = builder.Entity<HomeTestimonialsSectionSettings>();
        testimonials.ToTable("HomeTestimonialsSectionSettings", table => table.HasCheckConstraint("CK_HomeTestimonialsSectionSettings_Singleton", "Id = 1"));
        testimonials.HasKey(x => x.Id);
        testimonials.Property(x => x.Id).ValueGeneratedNever();
        testimonials.Property(x => x.Title).IsRequired().HasMaxLength(120);
        testimonials.Property(x => x.Description).IsRequired().HasMaxLength(1000);
        var collection = builder.Entity<TestimonialEntity>();
        collection.ToTable("Testimonials", table => table.HasCheckConstraint("CK_Testimonials_Order", "DisplayOrder > 0"));
        collection.HasKey(x => x.Id);
        collection.HasIndex(x => x.DisplayOrder);
        collection.Property(x => x.Attribution).IsRequired().HasMaxLength(180);
        collection.Property(x => x.Quote).IsRequired().HasMaxLength(1600);
        collection.Property(x => x.UpdatedAtUtc).IsConcurrencyToken();
        var partnerCollection = builder.Entity<PartnerEntity>();
        partnerCollection.ToTable("Partners", table => table.HasCheckConstraint("CK_Partners_Order", "DisplayOrder > 0"));
        partnerCollection.HasKey(x => x.Id);
        partnerCollection.HasIndex(x => x.DisplayOrder);
        partnerCollection.Property(x => x.Name).IsRequired().HasMaxLength(80);
        partnerCollection.Property(x => x.Description).IsRequired().HasMaxLength(200);
        partnerCollection.Property(x => x.ImagePath).IsRequired().HasMaxLength(200);
        partnerCollection.Property(x => x.Href).HasMaxLength(500);
        partnerCollection.Property(x => x.UpdatedAtUtc).IsConcurrencyToken();
        var partnerInitialization = builder.Entity<PartnerInitializationState>();
        partnerInitialization.ToTable("PartnerInitializationState", table => table.HasCheckConstraint("CK_PartnerInitializationState_Singleton", "Id = 1"));
        partnerInitialization.HasKey(x => x.Id);
        partnerInitialization.Property(x => x.Id).ValueGeneratedNever();
        var initialization = builder.Entity<TestimonialInitializationState>();
        initialization.ToTable("TestimonialInitializationState", table => table.HasCheckConstraint("CK_TestimonialInitializationState_Singleton", "Id = 1"));
        initialization.HasKey(x => x.Id);
        initialization.Property(x => x.Id).ValueGeneratedNever();
    }
}
